package build

import (
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"
)

// site is the complete output of a build, rendered in memory before
// anything in docs/ is touched.
type site struct {
	// dirs and files are slash paths relative to docs/, in walk order.
	dirs  []string
	files []outputFile
}

type outputFile struct {
	path string
	// copyFrom is the source of a file that is copied as it is. Its
	// content is not read into memory. Pages have content instead.
	copyFrom string
	content  []byte
}

// render reads every file in src and renders the pages. problems lists
// everything that went wrong, each prefixed with the source file name.
func render(src string) (*site, []string) {
	r := newRenderer(src)
	defer r.close()

	s := &site{}
	var problems []string
	seen := map[string]bool{}
	addProblem := func(p string) {
		if !seen[p] {
			seen[p] = true
			problems = append(problems, p)
		}
	}
	sourceOf := map[string]string{} // output path -> source name, to find clashes

	err := filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, p)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		if rel == "." {
			return nil
		}
		// Like piko, only the top-level folders are left out.
		if rel == "_includes" || rel == "_layouts" {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if d.IsDir() {
			s.dirs = append(s.dirs, rel)
			return nil
		}
		if !isRegularFile(p, d) {
			return nil
		}

		name := "src/" + rel
		out := rel
		if path.Ext(rel) == ".md" {
			out = strings.TrimSuffix(rel, ".md") + ".html"
		}
		if out == siteContentFile {
			addProblem(fmt.Sprintf("%s: docs/%s is generated by build, so it can't have a source", name, siteContentFile))
			return nil
		}
		// A clash is reported, and the page is still rendered so that its
		// own problems are reported too.
		if other, ok := sourceOf[out]; ok {
			addProblem(fmt.Sprintf("%s and %s both build docs/%s", other, name, out))
		}
		sourceOf[out] = name

		if !isPage(rel) {
			s.files = append(s.files, outputFile{path: out, copyFrom: p})
			return nil
		}
		text, err := os.ReadFile(p)
		if err != nil {
			addProblem(fmt.Sprintf("%s: %v", name, err))
			return nil
		}
		content, pageProblems := r.renderPage(string(text), path.Ext(rel) == ".md")
		for _, msg := range pageProblems {
			addProblem(name + ": " + msg)
		}
		s.files = append(s.files, outputFile{path: out, content: []byte(content)})
		return nil
	})
	if err != nil {
		addProblem(fmt.Sprintf("src: %v", err))
	}

	// Renaming .md to .html can change where a file sorts among its
	// siblings, and site_content.json lists pages in walk order of docs/.
	slices.SortFunc(s.files, func(a, b outputFile) int { return compareWalkOrder(a.path, b.path) })
	return s, problems
}

func isPage(rel string) bool {
	switch path.Ext(rel) {
	case ".html", ".svg", ".md":
		return true
	}
	return false
}

// isRegularFile reports whether d is a regular file or a symlink to one.
// Symlinked folders are not followed.
func isRegularFile(p string, d fs.DirEntry) bool {
	if d.Type().IsRegular() {
		return true
	}
	if d.Type()&fs.ModeSymlink == 0 {
		return false
	}
	info, err := os.Stat(p)
	return err == nil && info.Mode().IsRegular()
}

// compareWalkOrder orders slash paths the way filepath.WalkDir visits
// them: names sorted, a folder's contents right after the folder.
func compareWalkOrder(a, b string) int {
	return slices.Compare(strings.Split(a, "/"), strings.Split(b, "/"))
}
